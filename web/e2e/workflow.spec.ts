import {test,expect} from '@playwright/test';
import fs from 'node:fs/promises';
test('설정 → 실제 작업 큐 → 누적 목록 → 상세 → 전체 CSV',async({page})=>{
  test.skip(!process.env.E2E_PASSWORD,'E2E runtime and password must be explicitly configured');
  await page.goto('/');
  await page.getByLabel('이메일',{exact:true}).fill('e2e@example.com');
  await page.getByLabel('비밀번호',{exact:true}).fill(process.env.E2E_PASSWORD!);
  await page.getByRole('button',{name:'로그인',exact:true}).click();
  await expect(page.getByRole('heading',{name:'연구 대시보드'})).toBeVisible();
  await page.getByRole('button',{name:'+ 수집 설정',exact:true}).click();
  const dialog=page.getByRole('dialog');
  await dialog.getByLabel('연구 주제').fill('EEG brain age');
  await dialog.getByLabel('키워드 · 쉼표로 구분').fill('EEG, brain age');
  await dialog.getByRole('button',{name:'실제 검색어 미리보기'}).click();
  await expect(dialog.getByText('(ti:EEG OR abs:EEG) AND (ti:"brain age" OR abs:"brain age")',{exact:true})).toBeVisible();
  await dialog.getByRole('button',{name:'수집 설정 저장'}).click();
  await expect(dialog).not.toBeVisible();
  await page.getByRole('button',{name:'지금 수집',exact:true}).first().click();
  await expect(page.getByRole('heading',{name:'실행 이력'})).toBeVisible();
  await expect(page.getByText('검색 결과 소진',{exact:true}).first()).toBeVisible({timeout:70000});
  await page.getByRole('button',{name:'누적 논문',exact:true}).click();
  await expect(page.getByRole('button',{name:'Population biology of plants.',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Multi-Electron Production',exact:false}).click();
  await expect(page.getByRole('dialog').getByRole('heading',{name:'초록 기반 AI 요약'})).toBeVisible();
  await expect(page.getByRole('dialog').getByText('연구 목적: HERA 충돌에서 다중 전자 생성을 연구한다.',{exact:false})).toBeVisible();
  await page.getByRole('button',{name:'닫기',exact:true}).click();
  const downloadEvent=page.waitForEvent('download');
  await page.getByRole('link',{name:'누적 전체 CSV',exact:true}).click();
  const download=await downloadEvent;
  expect(download.suggestedFilename()).toMatch(/^papers_\d{8}_\d{4}\.csv$/);
  const bytes=await fs.readFile((await download.path())!);
  expect(bytes.subarray(0,3).toString('hex')).toBe('efbbbf');
  expect(bytes.toString('utf8')).toContain('제목,저널,저널 IF 지수,발표년도,DOI,초록,AI 논문 요약');
  expect(bytes.toString('utf8')).toContain('Population biology of plants.');
  await page.getByLabel('제목',{exact:true}).fill('Multi-Electron');
  await page.getByRole('button',{name:'필터 적용'}).click();
  await expect(page.getByRole('button',{name:'Population biology of plants.',exact:true})).not.toBeVisible();
  const filteredEvent=page.waitForEvent('download');
  await page.getByRole('link',{name:'필터 결과 CSV',exact:true}).click();
  const filtered=await filteredEvent;
  expect((await fs.readFile((await filtered.path())!)).toString('utf8')).not.toContain('Population biology of plants.');
  await page.screenshot({path:'test-results/library-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await expect(page.getByRole('heading',{name:'누적 논문',exact:true})).toBeVisible();
  await page.screenshot({path:'test-results/library-mobile.png',fullPage:true});
});
